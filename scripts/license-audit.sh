#!/usr/bin/env bash
# License 审计脚本：扫描全部依赖 License，生成 LICENSE-THIRD-PARTY.md
# 使用 go-licenses 工具（需先 go install github.com/google/go-licenses@latest）
set -euo pipefail

# 1. 检查 go-licenses 是否安装
if ! command -v go-licenses &> /dev/null; then
    echo "Installing go-licenses..."
    go install github.com/google/go-licenses@latest
fi

# 2. 生成 CSV 报告
echo "Generating license report..."
go-licenses csv ./... > /tmp/third_party_licenses.csv

# 3. 转换为 Markdown 表格
echo "# Third Party Licenses" > LICENSE-THIRD-PARTY.md
echo "" >> LICENSE-THIRD-PARTY.md
echo "> Auto-generated by scripts/license-audit.sh" >> LICENSE-THIRD-PARTY.md
echo "> Whale Code uses the following open-source libraries:" >> LICENSE-THIRD-PARTY.md
echo "" >> LICENSE-THIRD-PARTY.md
echo "| Package | License | Source |" >> LICENSE-THIRD-PARTY.md
echo "|---------|---------|--------|" >> LICENSE-THIRD-PARTY.md

while IFS=',' read -r pkg license url; do
    echo "| $pkg | $license | $url |" >> LICENSE-THIRD-PARTY.md
done < /tmp/third_party_licenses.csv

echo "" >> LICENSE-THIRD-PARTY.md
echo "## High Risk License Check" >> LICENSE-THIRD-PARTY.md
echo "" >> LICENSE-THIRD-PARTY.md

# 4. 检查高风险 License
HIGH_RISK=$(grep -iE "GPL|AGPL|SSPL|BSL" /tmp/third_party_licenses.csv || true)
if [ -n "$HIGH_RISK" ]; then
    echo "⚠️ Found high-risk licenses:" >> LICENSE-THIRD-PARTY.md
    echo '```' >> LICENSE-THIRD-PARTY.md
    echo "$HIGH_RISK" >> LICENSE-THIRD-PARTY.md
    echo '```' >> LICENSE-THIRD-PARTY.md
    echo "⚠️ WARNING: High-risk licenses detected! Please review."
else
    echo "✅ No high-risk licenses (GPL/AGPL/SSPL/BSL) found." >> LICENSE-THIRD-PARTY.md
fi

echo "Done! See LICENSE-THIRD-PARTY.md"
