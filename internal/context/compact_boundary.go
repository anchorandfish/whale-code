// Package context — compactBoundary semantic slicing (P1-1 / C7 contract).
//
// When the AICompactor compacts messages, it inserts a summary message
// marked with Subtype="compact_boundary". This allows downstream consumers
// to slice the conversation at semantic boundaries — everything before the
// last compact_boundary was summarized; everything after is recent context.
//
// GetMessagesAfterCompactBoundary finds the last compact_boundary marker
// and returns the messages from that point onward. CompactionPipeline.Execute
// calls this as step 0 to avoid re-compacting already-summarized prefixes.
package context

import (
	"github.com/anchorandfish/whale-code/internal/session"
)

// CompactMetadata stores metadata about a compaction operation, attached
// to the compact_boundary marker message's Metadata map (P1-1 / C7).
//
// Per C7: CompactMetadata is stored in session.Message.Metadata (a
// map[string]interface{}), not as a separate struct field. The keys are:
//   - "compact_trigger": why compaction was triggered (e.g. "auto", "manual",
//     "phase3", "reactive").
//   - "compact_pre_tokens": estimated token count before compaction.
//   - "compact_post_tokens": estimated token count after compaction.
//   - "compact_user_context": optional user-supplied context string
//     (e.g. a /compact reason or focus hint). May be empty.
//   - "compact_messages_summarized": number of messages that were summarized.
type CompactMetadata struct {
	Trigger            string `json:"compact_trigger"`
	PreTokens          int    `json:"compact_pre_tokens"`
	PostTokens         int    `json:"compact_post_tokens"`
	UserContext        string `json:"compact_user_context"`
	MessagesSummarized int    `json:"compact_messages_summarized"`
}

// SubtypeCompactBoundary is the session.Message.Subtype value that marks
// a compaction boundary (P1-1 / C7). Messages with this subtype are
// summaries of prior conversation turns.
const SubtypeCompactBoundary = "compact_boundary"

// SubtypeCollapseSummary is the session.Message.Subtype value that marks
// a collapse summary (P1-1). Messages with this subtype are generated by
// the ContextCollapseManager's staging/blocking collapse flow.
const SubtypeCollapseSummary = "collapse_summary"

// GetMessagesAfterCompactBoundary finds the last message with
// Subtype="compact_boundary" in the slice and returns all messages from
// that point onward (inclusive of the boundary marker) (P1-1).
//
// If no compact_boundary marker is found, the entire slice is returned
// unchanged (no slicing occurs).
//
// This is used by CompactionPipeline.Execute as step 0 to avoid
// re-compacting already-summarized prefixes: once a prefix has been
// summarized into a compact_boundary message, there is no need to compact
// it again — only the messages after the boundary need attention.
//
// The search is from the END of the slice (most recent boundary first)
// because multiple compactions may occur over a session's lifetime; we
// want the most recent boundary, not the oldest.
func GetMessagesAfterCompactBoundary(messages []session.Message) []session.Message {
	for i := len(messages) - 1; i >= 0; i-- {
		if messages[i].Subtype == SubtypeCompactBoundary {
			return messages[i:]
		}
	}
	return messages
}

// FindLastCompactBoundaryIndex returns the index of the last message with
// Subtype="compact_boundary", or -1 if none exists (P1-1).
func FindLastCompactBoundaryIndex(messages []session.Message) int {
	for i := len(messages) - 1; i >= 0; i-- {
		if messages[i].Subtype == SubtypeCompactBoundary {
			return i
		}
	}
	return -1
}

// HasCompactBoundary returns true if the message slice contains at least
// one compact_boundary marker (P1-1).
func HasCompactBoundary(messages []session.Message) bool {
	return FindLastCompactBoundaryIndex(messages) >= 0
}

// SetCompactBoundaryMetadata sets the CompactMetadata fields on a message's
// Metadata map and marks it as a compact_boundary (P1-1 / C7).
//
// This is called by AICompactor.Compact when creating the summary message.
// The message's Subtype is set to SubtypeCompactBoundary and the metadata
// fields are populated from the CompactMetadata struct.
func SetCompactBoundaryMetadata(msg *session.Message, meta CompactMetadata) {
	msg.Subtype = SubtypeCompactBoundary
	if msg.Metadata == nil {
		msg.Metadata = make(map[string]interface{})
	}
	msg.Metadata["compact_trigger"] = meta.Trigger
	msg.Metadata["compact_pre_tokens"] = meta.PreTokens
	msg.Metadata["compact_post_tokens"] = meta.PostTokens
	msg.Metadata["compact_messages_summarized"] = meta.MessagesSummarized
	if meta.UserContext != "" {
		msg.Metadata["compact_user_context"] = meta.UserContext
	}
}
